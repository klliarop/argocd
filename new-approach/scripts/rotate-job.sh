#!/usr/bin/env bash
# rotate-job.sh
# Prepares the pull secret rotation for a single environment.
# Merges the new pull secret with existing registry credentials,
# writes the ConfigMap YAML, and updates the Job timestamp.
# After this script, just git add + commit + push to trigger ArgoCD.
#
# Usage:
#   ./new-approach/scripts/rotate-job.sh <env> <path-to-new-pull-secret.json>
#
# Prerequisites:
#   - oc logged in to the target cluster
#   - jq on PATH
#   - podman or docker on PATH (for pull test)
set -euo pipefail

SCRIPT_DIR="$(cd "$(dirname "$0")" && pwd)"
ROOT_DIR="$(cd "${SCRIPT_DIR}/../.." && pwd)"
NEW_APPROACH_DIR="${ROOT_DIR}/new-approach"

GREEN='\033[0;32m'; YELLOW='\033[1;33m'; RED='\033[0;31m'; NC='\033[0m'
info()    { echo -e "${GREEN}==>${NC} $*"; }
warn()    { echo -e "${YELLOW}WARN:${NC} $*"; }
error()   { echo -e "${RED}ERROR:${NC} $*"; exit 1; }
section() { echo ""; echo "────────────────────────────────────────"; echo "  $*"; echo "────────────────────────────────────────"; }

# ── Args ─────────────────────────────────────────────────────────────────────
[[ $# -lt 2 ]] && { echo "Usage: $0 <env> <path-to-new-pull-secret.json>"; echo "  env: uat | pld | dr"; exit 1; }

ENV="$1"
NEW_SECRET_FILE="$(realpath "$2")"
VALID_ENVS=("uat" "pld" "dr")
VALID=false
for v in "${VALID_ENVS[@]}"; do [[ "$ENV" == "$v" ]] && VALID=true && break; done
[[ "$VALID" == "false" ]] && error "Unknown environment '$ENV'. Must be one of: uat, pld, dr"
[[ ! -f "$NEW_SECRET_FILE" ]] && error "File not found: $NEW_SECRET_FILE"

command -v oc  &>/dev/null || error "oc not found"
command -v jq  &>/dev/null || error "jq not found"

info "Environment : $ENV"
info "Cluster     : $(oc whoami --show-server)"
info "New secret  : $NEW_SECRET_FILE"

# ── Step 1: Backup ────────────────────────────────────────────────────────────
section "Step 1/4 — Backup current pull secret"
BACKUP_DIR="${ROOT_DIR}/backups"
mkdir -p "$BACKUP_DIR"
TIMESTAMP=$(date +"%Y%m%d-%H%M%S")
BACKUP_FILE="${BACKUP_DIR}/pull-secret-${ENV}-${TIMESTAMP}.json"

oc get secret/pull-secret -n openshift-config \
  --template='{{index .data ".dockerconfigjson" | base64decode}}' \
  > "$BACKUP_FILE"
jq . "$BACKUP_FILE" > "${BACKUP_FILE}.tmp" && mv "${BACKUP_FILE}.tmp" "$BACKUP_FILE"
info "Backup: $BACKUP_FILE"
info "Current registries:"
jq '.auths | keys' "$BACKUP_FILE"

# ── Step 2: Validate ──────────────────────────────────────────────────────────
section "Step 2/4 — Validate new pull secret"
jq -e '.auths' "$NEW_SECRET_FILE" > /dev/null 2>&1 \
  || error "Not a valid pull secret JSON (missing .auths)"

info "New secret registries:"
jq '.auths | keys' "$NEW_SECRET_FILE"

PULLER=""
command -v podman &>/dev/null && PULLER="podman"
command -v docker &>/dev/null && [[ -z "$PULLER" ]] && PULLER="docker"

if [[ -n "$PULLER" ]]; then
  info "Testing image pull using $PULLER..."
  $PULLER pull --authfile "$NEW_SECRET_FILE" registry.redhat.io/ubi8/ubi:latest \
    && info "Image pull succeeded." \
    || error "Image pull FAILED — check the new pull secret."
else
  warn "No podman/docker found — skipping image pull test."
fi

# ── Step 3: Merge ─────────────────────────────────────────────────────────────
section "Step 3/4 — Merge with existing registry credentials"
MERGED_FILE=$(mktemp /tmp/merged-pull-secret-XXXXXX.json)
trap 'rm -f "$MERGED_FILE"' EXIT

jq -s '{auths: (.[0].auths + .[1].auths)}' \
  "$NEW_SECRET_FILE" "$BACKUP_FILE" > "$MERGED_FILE"

info "Merged registries:"
jq '.auths | keys' "$MERGED_FILE"

# Warn if any existing registry was dropped
MISSING=$(jq -r --slurpfile b "$BACKUP_FILE" \
  '($b[0].auths | keys) - (.auths | keys) | .[]' "$MERGED_FILE" 2>/dev/null || true)
[[ -n "$MISSING" ]] && warn "These registries from the backup are missing in the merge: $MISSING"

# ── Step 4: Write ConfigMap ───────────────────────────────────────────────────
section "Step 4/4 — Write ConfigMap and update Job timestamp"

OVERLAY_DIR="${NEW_APPROACH_DIR}/gitops/overlays/${ENV}"
CM_FILE="${OVERLAY_DIR}/pull-secret-cm.yaml"
JOB_FILE="${NEW_APPROACH_DIR}/gitops/base/rotation-job.yaml"

# base64-encode the merged secret (no line wrapping)
B64=$(base64 -w 0 < "$MERGED_FILE")

# Write the ConfigMap
cat > "$CM_FILE" <<EOF
# ConfigMap holding the merged pull secret data.
# Generated by: ./new-approach/scripts/rotate-job.sh ${ENV} on $(date -u +"%Y-%m-%dT%H:%M:%SZ")
# This repo must be PRIVATE — this data is base64-encoded, not encrypted.
apiVersion: v1
kind: ConfigMap
metadata:
  name: pull-secret-data
  namespace: openshift-config
  labels:
    environment: ${ENV}
    rotation-timestamp: "${TIMESTAMP}"
binaryData:
  .dockerconfigjson: ${B64}
EOF

info "ConfigMap written: $CM_FILE"

# Update Job name with new timestamp so ArgoCD treats it as a new Job
sed -i "s/pull-secret-rotation-[0-9]*/pull-secret-rotation-${TIMESTAMP}/" "$JOB_FILE" \
  || sed -i "s/pull-secret-rotation-TIMESTAMP/pull-secret-rotation-${TIMESTAMP}/" "$JOB_FILE"

info "Job timestamp updated: pull-secret-rotation-${TIMESTAMP}"

# ── Done ──────────────────────────────────────────────────────────────────────
echo ""
echo -e "${GREEN}✓ Ready to deploy rotation for ${ENV}${NC}"
echo ""
echo "  Run these commands to trigger ArgoCD:"
echo ""
echo "    git add new-approach/gitops/overlays/${ENV}/pull-secret-cm.yaml"
echo "    git add new-approach/gitops/base/rotation-job.yaml"
echo "    git commit -m \"chore: rotate pull secret for ${ENV} [$(date +%Y-%m-%d)]\""
echo "    git push"
echo ""
echo "  Then monitor:"
echo "    oc get job -n openshift-config | grep pull-secret-rotation"
echo "    oc logs -n openshift-config job/pull-secret-rotation-${TIMESTAMP}"
echo "    oc get secret pull-secret -n openshift-config \\"
echo "      --template='{{index .data \".dockerconfigjson\" | base64decode}}' | jq '.auths | keys'"
